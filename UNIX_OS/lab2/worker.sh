#!/bin/sh
# Конкурентное создание и удаление файлов в общем каталоге.
#
# В бесконечном цикле с паузой в одну секунду между операциями:
#   1) под блокировкой flock выбирается первое свободное имя из 001, 002, ...
#      и создаётся файл с идентификатором контейнера и порядковым номером;
#   2) созданный файл удаляется.
#
# Переменные окружения:
#   SHARED_DIR — общий каталог (по умолчанию /shared)

DIR=${SHARED_DIR:-/shared}
LOCK=$DIR/.lock          # служебный файл синхронизации

# Случайный идентификатор контейнера: 16 шестнадцатеричных символов.
ID=$(head -c 8 /dev/urandom | od -An -tx1 | tr -d ' \n')

CURRENT=
log() { printf '[%s] %s\n' "$ID" "$*"; }

# Контейнер останавливается сигналом TERM (docker stop). Процесс с PID 1
# игнорирует сигналы без обработчика, поэтому обработчик обязателен.
# При остановке удаляем свой текущий файл, чтобы не оставлять мусор.
on_exit() {
    [ -n "$CURRENT" ] && rm -f -- "$DIR/$CURRENT"
    log "остановлен"
    exit 0
}
trap on_exit INT TERM HUP

# Паузу делаем через wait, чтобы сигнал обрабатывался сразу, а не после sleep.
pause() {
    sleep 1 &
    wait $!
}

mkdir -p -- "$DIR" || exit 1

# Дескриптор 9 открыт на весь срок жизни скрипта: блокировка берётся и
# снимается вызовами flock, без порождения подоболочек на каждый шаг.
exec 9>>"$LOCK" || exit 1

log "запущен, каталог $DIR"
n=0
while :; do
    n=$((n + 1))
    content="$ID $n"

    # ---- атомарный участок: поиск имени и создание файла ----
    flock -x 9 || exit 1
    i=1
    while :; do
        name=$(printf '%03d' "$i")
        [ -e "$DIR/$name" ] || break
        i=$((i + 1))
    done
    printf '%s\n' "$content" > "$DIR/$name"
    flock -u 9
    # ---- конец атомарного участка ----

    CURRENT=$name
    log "создан $name: $content"

    pause

    rm -f -- "$DIR/$name"
    CURRENT=
    log "удалён $name"

    pause
done
